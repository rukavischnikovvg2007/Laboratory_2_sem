"""
НЕДЕЛЯ 6, ЧАСТЬ 0: Диагностика проблемы append
Показывает, почему при повторном запуске строк становится в 2 раза больше
"""

import pandas as pd
import os

print("="*60)
print("ДИАГНОСТИКА: Проблема append")
print("="*60)

# Удаляем старый файл, если есть
if os.path.exists("out.csv"):
    os.remove("out.csv")
    print("🗑️ Старый файл out.csv удален")

# Создаем данные
df = pd.DataFrame({"id": [1, 2], "v": [10, 20]})

print("\n📊 Данные для загрузки:")
print(df)
print(f"Количество строк: {len(df)}")

# ------------------------------------------------------------
# ПРОБЛЕМНЫЙ КОД: append без контроля
# ------------------------------------------------------------
print("\n" + "="*60)
print("ШАГ 1: ЗАГРУЗКА С mode='a' (append)")
print("="*60)

# ПЕРВЫЙ ЗАПУСК
print("\n▶️ ПЕРВЫЙ ЗАПУСК:")
df.to_csv("out.csv", mode="a", header=True, index=False)
print("   Данные записаны в out.csv")

# ВТОРОЙ ЗАПУСК
print("\n▶️ ВТОРОЙ ЗАПУСК (те же данные):")
df.to_csv("out.csv", mode="a", header=False, index=False)
print("   Данные ДОПИСАНЫ в out.csv")

# Проверяем результат
print("\n📋 СОДЕРЖИМОЕ out.csv:")
with open("out.csv", "r") as f:
    print(f.read())

df_result = pd.read_csv("out.csv")
print(f"\n📊 ИТОГ: {len(df_result)} строк (ожидалось 2, но после 2 запусков стало 4!)")

print("\n❌ ПРОБЛЕМА: При повторном запуске данные дописались, а не перезаписались!")
print("   Идемпотентность нарушена — одинаковые входные данные дают разный результат")

# ------------------------------------------------------------
# ИСПРАВЛЕНИЕ: перезапись вместо append
# ------------------------------------------------------------
print("\n" + "="*60)
print("ШАГ 2: ИСПРАВЛЕНИЕ — перезапись вместо append")
print("="*60)

# Удаляем старый файл
if os.path.exists("out.csv"):
    os.remove("out.csv")

# ПЕРВЫЙ ЗАПУСК
print("\n▶️ ПЕРВЫЙ ЗАПУСК:")
df.to_csv("out.csv", index=False)
print("   Данные записаны в out.csv")

# ВТОРОЙ ЗАПУСК (те же данные)
print("\n▶️ ВТОРОЙ ЗАПУСК (те же данные):")
df.to_csv("out.csv", index=False)  # перезапись, а не append!
print("   Данные ПЕРЕЗАПИСАНЫ в out.csv")

df_result = pd.read_csv("out.csv")
print(f"\n📊 ИТОГ: {len(df_result)} строк (после 2 запусков — все еще 2 строки!)")

print("\n✅ ИСПРАВЛЕНО: При повторном запуске данные перезаписываются")
print("   Идемпотентность обеспечена — одинаковые входные данные дают одинаковый результат")

# ------------------------------------------------------------
# ВЫВОДЫ
# ------------------------------------------------------------
print("\n" + "="*60)
print("📝 ВЫВОДЫ:")
print("="*60)
print("""
1. Проблема: mode='a' (append) добавляет строки, не проверяя, были ли они уже
2. Результат: после 2 запусков — 4 строки, после 3 — 6 и т.д.
3. Идемпотентность: свойство системы давать одинаковый результат при повторных запусках
4. Решение: использовать перезапись (replace) или дедупликацию по ключу
""")

# Чистим за собой
os.remove("out.csv")
