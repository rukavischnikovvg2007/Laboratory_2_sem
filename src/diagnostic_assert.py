"""
НЕДЕЛЯ 8, ЧАСТЬ 0: Диагностика ошибок в assert
Показывает, как тест может проходить, даже когда данные плохие
"""

import pandas as pd

print("="*60)
print("ДИАГНОСТИКА: Почему тест всегда PASS?")
print("="*60)

# ------------------------------------------------------------
# 1. ПРОБЛЕМНЫЙ КОД: забыли скобки
# ------------------------------------------------------------
print("\n1. ПРОБЛЕМНЫЙ ТЕСТ (забыли скобки)")

df = pd.DataFrame({"x": [1, None, 3]})
print("Данные:")
print(df)

print("\nПроверка: assert df['x'].notna")
print("df['x'].notna без скобок — это объект метода, а не результат!")

try:
    # Это НЕПРАВИЛЬНО! notna без скобок
    assert df["x"].notna, "x has nulls"
    print("❌ ТЕСТ ПРОШЕЛ! (хотя в данных есть NULL)")
except AssertionError:
    print("✅ ТЕСТ УПАЛ")

print("\nПочему так произошло?")
print("   df['x'].notna (без скобок) → возвращает метод, а не результат")
print("   Метод считается 'истинным' (truthy), поэтому assert проходит")

# ------------------------------------------------------------
# 2. ИСПРАВЛЕННЫЙ КОД: со скобками
# ------------------------------------------------------------
print("\n" + "="*60)
print("2. ИСПРАВЛЕННЫЙ ТЕСТ (со скобками)")

print("\nПроверка: assert df['x'].notna().all()")
print("df['x'].notna() со скобками — возвращает Series булевых значений")
print(".all() — проверяет, что ВСЕ значения True")

try:
    assert df["x"].notna().all(), "x has nulls"
    print("✅ ТЕСТ ПРОШЕЛ (нет NULL)")
except AssertionError:
    print("❌ ТЕСТ УПАЛ! (обнаружены NULL)")

# ------------------------------------------------------------
# 3. ПРАВИЛЬНЫЙ ТЕСТ НА ХОРОШИХ ДАННЫХ
# ------------------------------------------------------------
print("\n" + "="*60)
print("3. ТЕСТ НА ХОРОШИХ ДАННЫХ")

df_good = pd.DataFrame({"x": [1, 2, 3]})
print("Данные:")
print(df_good)

try:
    assert df_good["x"].notna().all(), "x has nulls"
    print("✅ ТЕСТ ПРОШЕЛ! (NULL нет)")
except AssertionError:
    print("❌ ТЕСТ УПАЛ")

# ------------------------------------------------------------
# ВЫВОДЫ
# ------------------------------------------------------------
print("\n" + "="*60)
print("📝 ВЫВОДЫ:")
print("="*60)
print("""
1. Всегда вызывайте методы со скобками: .notna() а не .notna
2. Для проверки всех значений используйте .all()
3. Хороший тест обязан падать на плохих данных
""")

print("="*60)
print("✅ ДИАГНОСТИКА ЗАВЕРШЕНА")
print("="*60)