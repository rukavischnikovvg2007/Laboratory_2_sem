print("\n1. ПРОБЛЕМНЫЙ КОД (ошибка в единицах)")

# Правильные данные: осадки в миллиметрах
precipitation_mm = 12.0  # 12 мм осадков

print(f"Правильные данные: {precipitation_mm} мм")

# Ошибка: кто-то решил, что это метры, и пытается перевести обратно
# Но делает это с ошибкой (умножает дважды)
precipitation_mm_wrong = precipitation_mm / 1000  # мм -> м
precipitation_mm_wrong = precipitation_mm_wrong * 1000 * 1000  # ошибочный обратный перевод

print(f"\n❌ ОШИБОЧНЫЕ ДАННЫЕ: {precipitation_mm_wrong} мм (вместо 12 мм)")
print(f"   Это в {precipitation_mm_wrong / precipitation_mm:.0f} раз больше правильного значения!")

print("\n❌ ПОЧЕМУ ЭТО ОПАСНО:")
print("   1. Код не падает — нет ошибки выполнения")
print("   2. Число остается числом — можно принять за реальные данные")
print("   3. '12000 мм' можно принять за просто большие осадки")
print("   4. Ошибка может жить годами, искажая аналитику")

# ------------------------------------------------------------
# 2. ИСПРАВЛЕННЫЙ КОД
# ------------------------------------------------------------
print("\n" + "="*60)
print("2. ИСПРАВЛЕННЫЙ КОД")
print("="*60)

precipitation_mm = 12.0
print(f"Исходные данные: {precipitation_mm} мм")

# Правильное преобразование
precipitation_m = precipitation_mm / 1000  # мм -> метры
print(f"В метрах: {precipitation_m} м")

# Обратное преобразование (один раз умножаем на 1000)
precipitation_mm_back = precipitation_m * 1000  # метры -> мм
print(f"Обратно в мм: {precipitation_mm_back} мм")

# Проверка с assert
assert abs(precipitation_mm_back - precipitation_mm) < 1e-9, "Ошибка преобразования единиц!"
print("\n✅ Преобразование корректно, assert прошел")

