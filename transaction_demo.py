"""
НЕДЕЛЯ 5, ЧАСТЬ 0: Диагностика транзакций
Цель: понять, почему без commit() данные могут не сохраниться
"""

import sqlite3
import os

print("="*70)
print("ДИАГНОСТИКА: Почему таблица пустая?")
print("="*70)

# Создаем временную базу данных
db_path = "example.db"
print(f"\n📁 Файл базы данных: {os.path.abspath(db_path)}")

# ------------------------------------------------------------
# ПРОБЛЕМНЫЙ КОД: без commit()
# ------------------------------------------------------------
print("\n" + "="*70)
print("ШАГ 1: ВСТАВКА ДАННЫХ БЕЗ commit()")
print("="*70)

# Открываем соединение
con = sqlite3.connect(db_path)
cur = con.cursor()

# Создаем таблицу
cur.execute("CREATE TABLE IF NOT EXISTS t(x INTEGER);")
con.commit()  # это сохраняется (создание таблицы)

# Удаляем старые данные
cur.execute("DELETE FROM t;")
con.commit()

# Вставляем данные
cur.execute("INSERT INTO t VALUES (42);")

# ⚠️ ВАЖНО: здесь НЕТ con.commit()!
print("✅ Данные вставлены, но НЕ СОХРАНЕНЫ (нет commit)")

# Закрываем соединение
con.close()
print("🔒 Соединение закрыто")

# ------------------------------------------------------------
# ПРОВЕРКА: открываем новое соединение
# ------------------------------------------------------------
print("\n" + "="*70)
print("ШАГ 2: ПРОВЕРКА ДАННЫХ (новое соединение)")
print("="*70)

# Открываем новое соединение
con2 = sqlite3.connect(db_path)
cur2 = con2.cursor()

# Проверяем, есть ли данные
cur2.execute("SELECT COUNT(*) FROM t;")
count = cur2.fetchone()[0]

print(f"📊 Количество записей в таблице: {count}")

if count == 0:
    print("❌ ДАННЫХ НЕТ! Без commit() изменения не сохранились!")
    print("   После закрытия соединения данные потерялись")
else:
    print("✅ Данные есть!")

con2.close()

# ------------------------------------------------------------
# ИСПРАВЛЕННЫЙ КОД: с commit()
# ------------------------------------------------------------
print("\n" + "="*70)
print("ШАГ 3: ИСПРАВЛЕННЫЙ КОД - С commit()")
print("="*70)

# Открываем новое соединение
con3 = sqlite3.connect(db_path)
cur3 = con3.cursor()

# Очищаем таблицу
cur3.execute("DELETE FROM t;")
con3.commit()

# Вставляем данные
cur3.execute("INSERT INTO t VALUES (42);")
con3.commit()  # ✅ ВАЖНО: сохраняем изменения!
print("✅ Данные вставлены и СОХРАНЕНЫ (с commit)")

# Закрываем
con3.close()
print("🔒 Соединение закрыто")

# ------------------------------------------------------------
# ПРОВЕРКА ПОСЛЕ ИСПРАВЛЕНИЯ
# ------------------------------------------------------------
print("\n" + "="*70)
print("ШАГ 4: ПРОВЕРКА ПОСЛЕ ИСПРАВЛЕНИЯ")
print("="*70)

# Открываем новое соединение
con4 = sqlite3.connect(db_path)
cur4 = con4.cursor()

cur4.execute("SELECT COUNT(*) FROM t;")
count = cur4.fetchone()[0]

print(f"📊 Количество записей в таблице: {count}")

if count == 1:
    print("✅ ДАННЫЕ СОХРАНИЛИСЬ!")
    print("   С commit() изменения переживают закрытие соединения")
else:
    print("❌ Что-то пошло не так...")

con4.close()

# ------------------------------------------------------------
# ЧИСТКА: удаляем временный файл
# ------------------------------------------------------------
print("\n" + "="*70)
print("ШАГ 5: ОЧИСТКА")
print("="*70)

try:
    os.remove(db_path)
    print(f"✅ Временный файл {db_path} удален")
except:
    pass

# ------------------------------------------------------------
# ВАЖНЫЕ ВЫВОДЫ
# ------------------------------------------------------------
print("\n" + "="*70)
print("📝 ВАЖНЫЕ ВЫВОДЫ")
print("="*70)

print("""
1. commit() - это фиксация изменений в базе данных
   • Без commit() изменения могут не сохраниться
   • При закрытии соединения данные теряются

2. "Пустая таблица" - частые причины:
   • Забыли commit()
   • Смотрим не в ту базу/таблицу
   • Загрузили один файл, проверяем другой

3. Безопасная практика:
   conn = sqlite3.connect("database.db")
   # ... выполняем операции ...
   conn.commit()  # ВСЕГДА вызываем commit!
   conn.close()
""")

print("="*70)
print("✅ ДИАГНОСТИКА ЗАВЕРШЕНА!")
print("="*70)