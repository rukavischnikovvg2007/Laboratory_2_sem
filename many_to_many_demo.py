"""
НЕДЕЛЯ 4, ЧАСТЬ 0: Диагностика many-to-many merge
Цель: понять, почему при join строк становится больше
"""

import pandas as pd

print("="*70)
print("ДИАГНОСТИКА: Проблема many-to-many merge")
print("="*70)

# ------------------------------------------------------------
# ШАГ 1: Создаем "проблемные" таблицы
# ------------------------------------------------------------

print("\n📊 ШАГ 1: Создаем тестовые данные")
print("-" * 50)

# Левая таблица - это наши основные данные
# Например: данные о продажах
left = pd.DataFrame({
    "id": [1, 1, 2],      # id товара (повторяется!)
    "value": [10, 11, 20] # сумма продажи
})

print("ЛЕВАЯ ТАБЛИЦА (основные данные):")
print(left)
print(f"Количество строк: {len(left)}")
print("\nПочему id=1 повторяется?")
print("Потому что товар с id=1 был продан дважды (две разные продажи)")

# Правая таблица - это справочник товаров
# Например: название товара
right = pd.DataFrame({
    "id": [1, 1, 2],      # id товара (тоже повторяется!)
    "name": ["Товар А", "Товар А_дубль", "Товар Б"]
})

print("\nПРАВАЯ ТАБЛИЦА (справочник):")
print(right)
print(f"Количество строк: {len(right)}")
print("\nПочему id=1 повторяется в справочнике?")
print("Потому что в справочнике ошибка: один и тот же товар записан дважды")

# ------------------------------------------------------------
# ШАГ 2: Выполняем проблемный join
# ------------------------------------------------------------

print("\n" + "="*70)
print("ШАГ 2: Выполняем JOIN (объединение таблиц)")
print("="*70)

# Делаем left join (оставляем все строки из левой таблицы)
merged = left.merge(right, on="id", how="left")

print(f"Было строк в левой таблице: {len(left)}")
print(f"Стало строк после join: {len(merged)}")
print(f"Увеличилось на: {len(merged) - len(left)} строк")

print("\nРезультат join:")
print(merged)

# ------------------------------------------------------------
# ШАГ 3: Объясняем, почему так произошло
# ------------------------------------------------------------

print("\n" + "="*70)
print("ШАГ 3: Почему строк стало больше?")
print("="*70)

print("""
Рассмотрим id=1:

В левой таблице (продажи):
- строка 1: id=1, value=10
- строка 2: id=1, value=11
Итого: 2 строки с id=1

В правой таблице (справочник):
- строка 1: id=1, name="Товар А"
- строка 2: id=1, name="Товар А_дубль"
Итого: 2 строки с id=1

Что происходит при join?
Каждая строка слева соединяется с КАЖДОЙ строкой справа:
- первая строка слева (10) соединяется с первой строкой справа → (10, Товар А)
- первая строка слева (10) соединяется со второй строкой справа → (10, Товар А_дубль)
- вторая строка слева (11) соединяется с первой строкой справа → (11, Товар А)
- вторая строка слева (11) соединяется со второй строкой справа → (11, Товар А_дубль)

Итого: 2 × 2 = 4 строки для id=1

Для id=2:
- слева: 1 строка
- справа: 1 строка
- результат: 1 × 1 = 1 строка

Общий итог: 4 + 1 = 5 строк (вместо исходных 3)
""")

# ------------------------------------------------------------
# ШАГ 4: Показываем, почему это проблема для аналитики
# ------------------------------------------------------------

print("\n" + "="*70)
print("ШАГ 4: Почему это проблема для аналитики?")
print("="*70)

print("""
ПРОБЛЕМА 1: Неправильная сумма
--------------------------------
Исходная сумма value для id=1: 10 + 11 = 21
После join сумма стала: 10 + 10 + 11 + 11 = 42 (удвоилась!)
Если посчитать общую сумму по id=1, получим 42 вместо 21

ПРОБЛЕМА 2: Неправильное среднее
--------------------------------
Исходное среднее: 21 / 2 = 10.5
После join: 42 / 4 = 10.5 (совпало по случайности, но если значения разные - не совпадет)

ПРОБЛЕМА 3: Неправильное количество записей
--------------------------------
Исходное количество продаж id=1: 2
После join: кажется, что продаж 4 (хотя на самом деле 2)

ПРОБЛЕМА 4: Искажение всех метрик
--------------------------------
Любая агрегация (sum, count, min, max, mean) будет искажена
Графики и дашборды покажут неверные данные
""")

# ------------------------------------------------------------
# ШАГ 5: Исправление - способ 1 (удаление дубликатов)
# ------------------------------------------------------------

print("\n" + "="*70)
print("ШАГ 5: ИСПРАВЛЕНИЕ - Способ 1: удаление дубликатов из справочника")
print("="*70)

print("Если дубликаты в справочнике - это ошибка, просто удаляем их:")

# Проверяем дубликаты
print("\nБыло строк в справочнике:", len(right))
print("Дубликатов по id:", right.duplicated(subset=["id"]).sum())

# Удаляем дубликаты
right_unique = right.drop_duplicates(subset=["id"])
print("Стало строк после удаления дубликатов:", len(right_unique))

print("\nСправочник после очистки:")
print(right_unique)

# Выполняем join заново
merged_fixed = left.merge(right_unique, on="id", how="left")

print(f"\nРезультат: {len(left)} → {len(merged_fixed)} строк")
print(merged_fixed)

print("\n✅ Теперь строк столько же, сколько было в левой таблице!")
print("   Сумма для id=1: 10 + 11 = 21 (правильно)")

# ------------------------------------------------------------
# ШАГ 6: Исправление - способ 2 (агрегация справочника)
# ------------------------------------------------------------

print("\n" + "="*70)
print("ШАГ 6: ИСПРАВЛЕНИЕ - Способ 2: агрегация справочника")
print("="*70)

print("""
Если дубликаты в справочнике - это не ошибка, а несколько значений для одного ключа,
нужно решить, как их объединить. Например:
- взять первое значение
- взять последнее
- объединить в список
- взять среднее (если числовые)
""")

# Агрегируем: берем первое значение для каждого id
right_agg = right.groupby("id").first().reset_index()

print("Справочник после агрегации (взяли первое значение):")
print(right_agg)

# Выполняем join
merged_fixed2 = left.merge(right_agg, on="id", how="left")

print(f"\nРезультат: {len(left)} → {len(merged_fixed2)} строк")
print(merged_fixed2)

# ------------------------------------------------------------
# ШАГ 7: Исправление - способ 3 (проверка перед join)
# ------------------------------------------------------------

print("\n" + "="*70)
print("ШАГ 7: ИСПРАВЛЕНИЕ - Способ 3: проверка перед join (validate)")
print("="*70)

print("""
В pandas есть параметр validate, который проверяет кардинальность соединения:

- validate="one_to_one" - проверяет, что ключи уникальны в обеих таблицах
- validate="one_to_many" - проверяет, что ключи уникальны в правой таблице
- validate="many_to_one" - проверяет, что ключи уникальны в левой таблице
- validate="many_to_many" - разрешает любые дубликаты

Если проверка не проходит, pandas выдаст ошибку.
""")

try:
    # Пытаемся выполнить join с проверкой
    merged_validated = left.merge(right, on="id", how="left", validate="one_to_many")
    print("✅ Проверка пройдена")
except Exception as e:
    print(f"❌ Ошибка при проверке: {e}")
    print("   Это хорошо! Мы узнали о проблеме до того, как получили неверные данные")

# ------------------------------------------------------------
# ИТОГ
# ------------------------------------------------------------

print("\n" + "="*70)
print("📝 ИТОГ ЧАСТИ 0: ЧТО НУЖНО ЗАПОМНИТЬ")
print("="*70)

print("""
1. Перед любым join всегда проверяйте уникальность ключей
   - В левой таблице (основные данные) ключ может повторяться
   - В правой таблице (справочник) ключ ДОЛЖЕН быть уникальным

2. Если строк после join стало больше - это почти всегда ошибка

3. Всегда проверяйте количество строк до и после:
   print(f"До: {len(df_left)} → После: {len(df_merged)}")

4. Используйте параметр validate для защиты:
   df_merged = df_left.merge(df_right, on="key", validate="many_to_one")

5. Если в справочнике есть дубликаты:
   - Удалите их: df_right.drop_duplicates(subset=["key"])
   - Или агрегируйте: df_right.groupby("key").first().reset_index()
""")

print("\n" + "="*70)
print("✅ ДИАГНОСТИКА ЗАВЕРШЕНА!")
print("="*70)